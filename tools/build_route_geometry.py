def simplify(points, tol):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-12
    idx, dmax = 0, 0.0
    for i in range(1, len(points) - 1):
        x0, y0 = points[i]
        d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm
        if d > dmax:
            idx, dmax = i, d
    if dmax > tol:
        left = simplify(points[: idx + 1], tol)
        right = simplify(points[idx:], tol)
        return left[:-1] + right
    return [points[0], points[-1]]


out = []
for leg_id, label, kind, way in LEGS:
    coords = ";".join(f"{P[k][1]},{P[k][0]}" for k in way)
    url = f"https://router.project-osrm.org/route/v1/driving/{coords}?overview=full&geometries=geojson"
    for attempt in range(4):
        try:
            with urllib.request.urlopen(url, timeout=60) as r:
                route = json.load(r)["routes"][0]
            break
        except Exception as exc:  # noqa: BLE001
            print("retry", leg_id, exc)
            time.sleep(5)
    pts = [(lat, lon) for lon, lat in route["geometry"]["coordinates"]]
    simple = simplify(pts, 0.0006)
    miles = route["distance"] / 1609.344
    print(f"{leg_id}: {len(pts)} -> {len(simple)} pts, {miles:.0f} mi, {route['duration']/3600:.2f} hr (free-flow)")
    out.append({
        "id": leg_id,
        "label": label,
        "kind": kind,
        "miles": round(miles),
        "coords": [[round(a, 4), round(b, 4)] for a, b in simple],
    })
    time.sleep(1)

